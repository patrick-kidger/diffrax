class Vern9(AbstractERK):
    r"""Verner's "most efficient" 9(8) method.

    9th order explicit Runge--Kutta method. Has an embedded 8th order method for
    adaptive step sizing. Uses 16 stages, and is not FSAL. Uses 3rd order Hermite
    interpolation for dense/ts output.

    This is a good choice for smooth problems that must be solved to tight tolerances
    (around `rtol=1e-9` or smaller), where it typically needs far fewer function
    evaluations than lower-order methods.

    !!! warning

        The interpolation is only 3rd order accurate. When using `SaveAt(ts=...)` or
        `SaveAt(dense=True)` the saved values between steps may therefore be less
        accurate than the solution at the end of each step.

    ??? cite "Reference"

        ```bibtex
        @article{verner2010numerically,
            title={Numerically optimal {R}unge--{K}utta pairs with interpolants},
            author={Verner, James H.},
            journal={Numerical Algorithms},
            volume={53},
            number={2},
            pages={383--396},
            year={2010},
            publisher={Springer}
        }
        ```

        Coefficients from <https://www.sfu.ca/~jverner/>.
    """

    tableau: ClassVar[ButcherTableau] = _vern9_tableau
    interpolation_cls: ClassVar[
        Callable[..., ThirdOrderHermitePolynomialInterpolation]
    ] = ThirdOrderHermitePolynomialInterpolation.from_k

    def order(self, terms):
        del terms
        return 9


